course = "Python Programming"
print(len(course))  # prints the length of characheters in the string
print(course[0])  # prints the first character of the string
print(course[-10])  # prints the 10th character from the end of the string
print(course[0:3])  # prints the first 3 characters of the string
print(course[0:])  # prints the first 5 characters of the string
print(course[:5])  # prints the first 5 characters of the string
print(course[:])  # prints the entire string
