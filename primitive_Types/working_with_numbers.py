import math

print(round(2.9))  # rounds the number to nearst integer
print(abs(-7.25))  # returns the positive value
print(math.ceil(2.2))  # upwards to its nearest integer
print(math.floor(2.2))  # downwards to its nearest integer
print(math.pi)  # prints the pi value 3.14
print(min(2, 10, 25))  # prints the minimum value
print(max(2, 10, 25))  # prints the maximum value
print(pow(4, 3))  # prints the power value 4 * 4 * 4 = 64
print(math.sqrt(25))  # prints the square root value of 25 is 5
print(math.log(10, 2))  # prints the log valude of 10
